def compute_effect(target: Path, lab: Path) -> dict:
    files, manifest = layer_files(target)
    current = {p: d for p, d in files.items() if p != oaw.MANIFEST_PATH}
    for relative in manifest.get("custom_files", []):
        path = oaw.joined(target, relative)
        if path.is_file():
            current[relative] = path.read_bytes()
    hosts = manifest.get("hosts", ["codex"])
    scratch = scratch_dir(lab, "effect-")
    try:
        default_target = scratch / "default-project"
        try:
            plan = oaw.plan_install(default_target, "minimal", False, hosts=hosts)
            oaw.apply_plan(plan, migrate=False)
            default_manifest = oaw.read_manifest(default_target)
        except oaw.InstallError as exc:
            raise CatalogError(f"Default recipe install failed: {exc}") from exc
        default = {p: oaw.joined(default_target, p).read_bytes() for p in default_manifest["managed_files"]}
    finally:
        rmtree(scratch)
    registry = load_registry(target)
    measured = [r for fid in registry.get("foods", {}) for r in load_evidence(target, fid) if core.evidence_class(r) == "live"]
    effect = core.effect_vs_default(core.install_inventory(current), core.install_inventory(default), measured)
    effect.update(computed_at=now_iso(), layer_hash=layer_hash(files),
                  default_recipe={"profile": "minimal", "with_improve": False, "hosts": hosts, "skills": oaw.default_skills("minimal", False)},
                  current_recipe={"profile": manifest.get("profile"), "with_improve": manifest.get("with_improve"),
                                  "skills": manifest.get("skills"), "hosts": hosts})
    save_json(target, ("effect.json",), effect)
    return effect


def effect_lines(effect: dict) -> list:
    lines = [f"effect vs default {effect['release']} (default recipe: minimal, skills {', '.join(effect['default_recipe']['skills'])})",
             f"  skills added: {', '.join(effect['skills']['added']) or 'none'} · removed: {', '.join(effect['skills']['removed']) or 'none'}"]
    for line in effect["lines"]:
        if line["metric"] == "quality":
            lines.append(f"  quality: {line['value']} [{line['level']}] {line['note']}")
            continue
        delta = "" if line["delta"] is None else f" ({line['delta']:+d})"
        lines.append(f"  {line['metric']}: {line['current']} vs {line['default']}{delta} [{line['level']}]" + (f" · {line['note']}" if line["note"] else ""))
    return lines


def cmd_effect(target: Path) -> dict:
    effect = compute_effect(target, lab_home(target))
    update_view(target)
    return {"status": "effect", "effect": effect, "lines": effect_lines(effect)}


def safe_effect(target: Path, lab: Path) -> dict:
    """The absorption-time evaluation (D12); a failure is recorded, never fatal after a change."""
    try:
        return effect_summary(compute_effect(target, lab))
    except (CatalogError, OSError, ValueError) as exc:
        return {"error": core.sanitize_text(str(exc), 200), "quality": "not measured", "skills": None, "lines": []}


def effect_summary(effect: dict) -> dict:
    return {"skills": effect["skills"], "quality": effect["quality"]["value"],
            "lines": [{k: line.get(k) for k in ("metric", "current", "default", "delta", "level", "value")} for line in effect["lines"]]}



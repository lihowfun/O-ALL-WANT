def dispatch(args) -> dict:
    target = project_target(getattr(args, "target", "."))
    command = args.command
    if command == "add":
        result = add_foods(target, args.urls, ref=args.ref)
        update_view(target)
        return result
    if command == "list":
        return cmd_list(target)
    if command == "show":
        return cmd_show(target, args.food)
    if command == "taste":
        return cmd_taste(target, args.food, args.ref)
    if command == "triage":
        return cmd_triage(target, args)
    if command == "import-report":
        return cmd_import_report(target, args.food, args.directory)
    if command == "plan":
        return cmd_plan(target, args.food)
    if command == "policy":
        return cmd_policy(target, args)
    if command == "absorb":
        return cmd_absorb(target, args.food, [c for c in args.components.split(",") if c.strip()], args.reason, args.apply)
    if command == "remove":
        return cmd_remove(target, args.name, args.reason, args.apply, food=args.food)
    if command == "readd":
        return cmd_readd(target, args.name, args.reason, args.apply)
    if command == "forget":
        return cmd_forget(target, args.food, args.reason, args.apply)
    if command == "builds":
        return cmd_builds(target)
    if command == "restore":
        return cmd_restore(target, args.build, args.apply)
    if command == "effect":
        return cmd_effect(target)
    if command == "view":
        return cmd_view(target)
    if command == "scout":
        if args.scout_command == "pick":
            return cmd_scout_pick(target, args.ranks)
        if args.scout_command == "list":
            return cmd_scout_list(target)
        return cmd_scout(target)
    if command in ("ui", "menu"):
        import catalog_ui_server
        if command == "menu":
            return catalog_ui_server.cmd_menu(target)
        if not 0 <= args.port <= 65535:
            raise CatalogError("--port must be between 0 and 65535.")
        return catalog_ui_server.cmd_ui(target, open_browser=not args.no_browser, port=args.port)
    raise CatalogError(f"Unknown command {command}")


def main(argv=None) -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="backslashreplace")
    args = parser().parse_args(argv)
    as_json = getattr(args, "json", False)
    try:
        if sys.version_info < (3, 10):
            raise CatalogError("Python 3.10+ is required.")
        result = dispatch(args)
        code = 0
    except NeedsConfirmation as exc:
        result, code = {"status": "needs-confirmation", "error": str(exc), "lines": [str(exc)]}, 4
    except (CatalogError, oaw.InstallError, core.SourceError, OSError, ValueError) as exc:
        result, code = {"status": "error", "error": str(exc), "lines": [f"catalog error: {exc}"]}, 2
    if as_json:
        print(json.dumps({k: v for k, v in result.items() if k != "lines"}, indent=2, ensure_ascii=False, default=str))
    else:
        stream = sys.stderr if code == 2 else sys.stdout
        print("\n".join(result.get("lines", [])), file=stream)
    return code


if __name__ == "__main__":
    raise SystemExit(main())

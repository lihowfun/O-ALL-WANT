def find_git(target: Path, lab: Path):
    entries = [p for p in os.environ.get("PATH", "").split(os.pathsep) if p and os.path.isabs(p)]
    found = shutil.which("git", path=os.pathsep.join(entries))
    if not found:
        return None
    resolved = Path(found).resolve()
    if _inside(resolved, target) or _inside(resolved, lab):
        raise CatalogError("Refusing a git executable inside the project or LAB_HOME.")
    return str(resolved)


def git_env(home: Path, empty_config: Path) -> dict:
    keep = ("PATH", "SYSTEMROOT", "SystemRoot", "WINDIR", "COMSPEC", "PATHEXT", "TEMP", "TMP", "LANG",
            "HTTP_PROXY", "HTTPS_PROXY", "NO_PROXY", "ALL_PROXY", "http_proxy", "https_proxy", "no_proxy",
            "SSL_CERT_FILE", "SSL_CERT_DIR", "GIT_SSL_CAINFO")
    env = {name: os.environ[name] for name in keep if name in os.environ}
    env.update({"GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": str(empty_config), "GIT_TERMINAL_PROMPT": "0",
                "GIT_LFS_SKIP_SMUDGE": "1", "GIT_ASKPASS": "", "SSH_ASKPASS": "", "GCM_INTERACTIVE": "never",
                "HOME": str(home), "XDG_CONFIG_HOME": str(home), "NoDefaultCurrentDirectoryInExePath": "1"})
    return env


def run_git(argv, *, cwd: Path, env: dict, data: bytes | None = None, timeout=600) -> bytes:
    try:
        if data is None:
            process = subprocess.run(argv, cwd=str(cwd), env=env, stdin=subprocess.DEVNULL, capture_output=True, timeout=timeout)
        else:
            process = subprocess.run(argv, cwd=str(cwd), env=env, input=data, capture_output=True, timeout=timeout)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise CatalogError(f"git could not run: {exc}") from exc
    if process.returncode:
        message = core.sanitize_text(process.stderr.decode("utf-8", "replace"), 300)
        verb = next((a for a in argv[1:] if a in ("init", "fetch", "rev-parse", "ls-tree", "cat-file")), "command")
        raise CatalogError(f"git {verb} failed: {message}")
    return process.stdout


def fetch_git(git: str, source: dict, ref, lab: Path) -> dict:
    """Hardened fetch: no hooks, no checkout, protocol allowlist; tar built from ls-tree/cat-file."""
    scratch = scratch_dir(lab, "fetch-")
    try:
        hooks, empty = scratch / "no-hooks", scratch / "empty.gitconfig"
        hooks.mkdir()
        empty.write_text("", encoding="utf-8")
        repo = scratch / "repo.git"
        env = git_env(scratch, empty)
        config = ["-c", f"core.hooksPath={hooks}", "-c", "protocol.allow=never", "-c", "protocol.https.allow=always",
                  "-c", "core.fsmonitor=false", "-c", "credential.helper=", "-c", "submodule.recurse=false"]
        if source["kind"] == "file":
            config += ["-c", "protocol.file.allow=always"]
        base = [git, *config]
        run_git(base + ["init", "--bare", "-q", str(repo)], cwd=scratch, env=env)
        wanted = ref or "HEAD"
        if not re.fullmatch(r"[A-Za-z0-9._/-]{1,200}", wanted) or wanted.startswith("-"):
            raise CatalogError("Unsafe ref.")
        run_git(base + ["-C", str(repo), "fetch", "-q", "--depth", "1", "--no-tags", "--no-recurse-submodules",
                        source["fetch_url"], wanted], cwd=scratch, env=env)
        commit = run_git(base + ["-C", str(repo), "rev-parse", "--verify", "FETCH_HEAD^{commit}"], cwd=scratch, env=env).decode().strip()
        if not re.fullmatch(r"[0-9a-f]{40}", commit) or (re.fullmatch(r"[0-9a-f]{40}", wanted) and wanted != commit):
            raise CatalogError("Fetched commit does not match the requested pin.")
        listing = run_git(base + ["-C", str(repo), "ls-tree", "-r", "-z", "--full-tree", commit], cwd=scratch, env=env)
        entries, symlinks, gitlinks, skipped = [], {}, [], []
        for raw in listing.split(b"\0"):
            if not raw:
                continue
            meta, _tab, raw_path = raw.partition(b"\t")
            mode, kind, oid = meta.decode().split()
            try:
                path = raw_path.decode("utf-8")
            except UnicodeDecodeError:
                skipped.append("undecodable#" + hashlib.sha256(raw_path).hexdigest()[:8])
                continue
            if mode == "160000":
                gitlinks.append(path)
            elif kind == "blob":
                entries.append((mode, oid, path))
        if len(entries) > core.LIMITS["max_files"]:
            raise CatalogError(f"Refused: {len(entries)} files > {core.LIMITS['max_files']} limit.")
        checks = run_git(base + ["-C", str(repo), "cat-file", "--batch-check"], cwd=scratch, env=env,
                         data="".join(f"{oid}\n" for _m, oid, _p in entries).encode())
        sizes = {}
        for line in checks.decode().splitlines():
            parts = line.split()
            if len(parts) == 3 and parts[1] == "blob":
                sizes[parts[0]] = int(parts[2])
        wanted_blobs = []
        for mode, oid, path in entries:
            if sizes.get(oid, 0) > core.LIMITS["max_file_bytes"]:
                skipped.append(path)
            else:
                wanted_blobs.append((mode, oid, path))
        if sum(sizes.get(oid, 0) for _m, oid, _p in wanted_blobs) > core.LIMITS["max_total_bytes"]:
            raise CatalogError("Refused: snapshot exceeds the 50 MB limit.")
        stream = run_git(base + ["-C", str(repo), "cat-file", "--batch"], cwd=scratch, env=env,
                         data="".join(f"{oid}\n" for _m, oid, _p in wanted_blobs).encode())
        blobs, offset = {}, 0
        while offset < len(stream):
            end = stream.index(b"\n", offset)
            header = stream[offset:end].decode().split()
            if len(header) != 3:
                raise CatalogError("git cat-file returned a missing or unexpected object.")
            oid, _kind, size = header
            start = end + 1
            blobs[oid] = stream[start:start + int(size)]
            offset = start + int(size) + 1
        files, modes = {}, {}
        for mode, oid, path in wanted_blobs:
            if mode == "120000":
                symlinks[path] = core.sanitize_text(blobs[oid].decode("utf-8", "replace"), 200)
            else:
                files[path], modes[path] = blobs[oid], mode
        return {"commit": commit, "integrity": "git-object-verified", "method": "git", "files": files, "modes": modes,
                "symlinks": symlinks, "gitlinks": gitlinks, "skipped": skipped}
    finally:
        rmtree(scratch)


def fetch_codeload(source: dict, ref) -> dict:
    """Fallback without git: a codeload tarball, marked unverified-against-commit."""
    if source["kind"] != "github":
        raise CatalogError("The tarball fallback only supports github.com sources.")
    url = f"{CODELOAD}/{urllib.parse.quote(source['owner'])}/{urllib.parse.quote(source['repo'])}/tar.gz/{urllib.parse.quote(ref or 'HEAD', safe='/')}"
    request = urllib.request.Request(url, headers={"User-Agent": "oaw-catalog/0"})
    try:
        with urllib.request.urlopen(request, timeout=60) as response:
            data = response.read(core.LIMITS["max_total_bytes"] + 1)
    except (urllib.error.URLError, OSError) as exc:
        raise CatalogError(f"Tarball download failed: {exc}") from exc
    if len(data) > core.LIMITS["max_total_bytes"]:
        raise CatalogError("Refused: tarball exceeds the 50 MB limit.")
    files, modes, symlinks, skipped = {}, {}, {}, []
    try:
        with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as archive:
            comment = str(archive.pax_headers.get("comment", ""))
            for member in archive.getmembers():
                parts = member.name.split("/", 1)
                if len(parts) < 2 or not parts[1]:
                    continue
                path = parts[1].rstrip("/")
                if member.isdir():
                    continue
                if member.issym():
                    symlinks[path] = core.sanitize_text(member.linkname, 200)
                elif not member.isreg():
                    skipped.append(path)
                elif member.size > core.LIMITS["max_file_bytes"]:
                    skipped.append(path)
                else:
                    handle = archive.extractfile(member)
                    files[path] = handle.read() if handle else b""
                    modes[path] = "100755" if member.mode & 0o111 else "100644"
                if len(files) > core.LIMITS["max_files"]:
                    raise CatalogError("Refused: too many files.")
    except (tarfile.TarError, EOFError, OSError) as exc:
        raise CatalogError(f"Tarball is not readable: {exc}") from exc
    commit = comment if re.fullmatch(r"[0-9a-f]{40}", comment) else None
    return {"commit": commit, "integrity": "unverified-against-commit", "method": "codeload", "files": files,
            "modes": modes, "symlinks": symlinks, "gitlinks": [], "skipped": skipped}


def build_tar(files: dict) -> bytes:
    """Deterministic tar of regular files: mode 0644, no owners, no times."""
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w", format=tarfile.PAX_FORMAT) as archive:
        for path in sorted(files):
            info = tarfile.TarInfo(path)
            info.size, info.mode, info.mtime, info.type = len(files[path]), 0o644, 0, tarfile.REGTYPE
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            archive.addfile(info, io.BytesIO(files[path]))
    return buffer.getvalue()


def read_tar(path: Path) -> dict:
    """Read regular members into memory. Nothing is ever extracted to disk."""
    files, seen = {}, set()
    try:
        with tarfile.open(path, mode="r:") as archive:
            for member in archive:
                if not member.isreg():
                    raise CatalogError(f"Sealed archive has a non-regular member: {core.sanitize_text(member.name, 80)}")
                problem = core.member_path_error(member.name, seen)
                if problem:
                    raise CatalogError(f"Sealed archive member refused ({problem}).")
                handle = archive.extractfile(member)
                files[member.name] = handle.read() if handle else b""
    except (tarfile.TarError, OSError) as exc:
        raise CatalogError(f"Sealed archive is not readable: {exc}") from exc
    return files


def seal(snapshot: dict, subdir=None) -> tuple:
    files, modes, skipped, seen = {}, {}, list(snapshot["skipped"]), set()
    prefix = (subdir.strip("/") + "/") if subdir else ""
    for path in sorted(snapshot["files"]):
        if prefix and not path.startswith(prefix):
            continue
        problem = core.member_path_error(path, seen)
        if problem:
            skipped.append(path if not core.member_path_error(path) else "unsafe#" + hashlib.sha256(path.encode()).hexdigest()[:8])
            continue
        files[path], modes[path] = snapshot["files"][path], snapshot["modes"].get(path, "100644")
    if len(files) > core.LIMITS["max_files"] or sum(len(v) for v in files.values()) > core.LIMITS["max_total_bytes"]:
        raise CatalogError("Refused: snapshot exceeds the archive limits.")
    if not files:
        raise CatalogError("Refused: the snapshot has no readable files.")
    return files, modes, skipped


# --------------------------------------------------------------------------- taste

def cmd_taste(target: Path, ident: str, ref=None) -> dict:
    try:
        return _taste(target, ident, ref)
    except CatalogError as exc:
        try:
            entry = resolve_food(load_registry(target), ident)
        except CatalogError:
            raise exc from None
        write_status(target, entry, "quarantine", 0, stop_reason=core.sanitize_text(str(exc), 200))
        raise


def _taste(target: Path, ident: str, ref=None) -> dict:
    registry = load_registry(target)
    entry = resolve_food(registry, ident)
    fid, source = entry["id"], entry["source"]
    lab = lab_home(target)
    write_status(target, entry, "quarantine", 0)
    git = find_git(target, lab)
    wanted = ref or source.get("requested_ref")
    errors = []
    snapshot = None
    if git:
        try:
            snapshot = fetch_git(git, source, wanted, lab)
        except CatalogError as exc:
            errors.append(str(exc))
    if snapshot is None:
        if source["kind"] != "github":
            raise CatalogError("Cannot fetch: " + ("; ".join(errors) or "git is not available"))
        snapshot = fetch_codeload(source, wanted)
        snapshot["fallback_reason"] = errors[0] if errors else "git is not available"
    files, modes, skipped = seal(snapshot, source.get("subdir"))
    hashes = {p: core.sha256_bytes(d) for p, d in files.items()}
    tree = core.tree_sha256(hashes)
    pin = snapshot["commit"] or "tree-" + tree[:12]
    folder = f"foods/{core.slug(fid)}/{pin}"
    tar_path, inventory_path = lab_path(lab, folder + "/source.tar"), lab_path(lab, folder + "/inventory.json")
    if tar_path.exists():
        previous = load_json(inventory_path, {})
        if previous.get("tree_sha256") != tree:
            raise CatalogError("Integrity failure: the same pin produced different bytes; the earlier snapshot is kept.")
    else:
        tar_bytes = build_tar(files)
        lab_write(lab, folder + "/source.tar", tar_bytes, readonly=True)
        inventory = {"schema_version": 1, "food": fid, "source_key": private_ref(source), "commit": snapshot["commit"],
                     "integrity": snapshot["integrity"], "method": snapshot["method"], "tree_sha256": tree,
                     "tar_sha256": core.sha256_bytes(tar_bytes), "fetched_at": now_iso(),
                     "files": [{"path": p, "sha256": hashes[p], "size": len(files[p]), "mode": modes[p]} for p in sorted(files)],
                     "symlinks": snapshot["symlinks"], "gitlinks": snapshot["gitlinks"], "skipped": skipped,
                     "fallback_reason": snapshot.get("fallback_reason")}
        lab_write(lab, folder + "/inventory.json", dump(inventory).encode("utf-8"), readonly=True)
    inventory = load_json(inventory_path, {})
    sealed = read_tar(tar_path)
    if core.tree_sha256({p: core.sha256_bytes(d) for p, d in sealed.items()}) != inventory.get("tree_sha256"):
        raise CatalogError("Integrity failure: the sealed archive does not match its inventory.")
    write_status(target, {**entry, "source": {**source, "commit": snapshot["commit"]}}, "static", 1)
    sealed_modes = {item["path"]: item["mode"] for item in inventory.get("files", [])}
    record = core.static_scan(sealed, food=fid, commit=snapshot["commit"], integrity=inventory["integrity"], modes=sealed_modes,
                              skipped=inventory.get("skipped", []), symlinks=inventory.get("symlinks", {}),
                              gitlinks=inventory.get("gitlinks", []))
    stamp = now_iso()
    record["recorded_at"] = stamp
    record["sealed"] = {"location": "LAB_HOME (outside the project)", "lab_ref": folder + "/source.tar",
                        "tar_sha256": inventory["tar_sha256"], "extracted": False, "executed": False}
    intake = {"schema_version": 1, "evidence_id": f"{fid}@{pin[:12]}/I0", "food": fid, "commit": snapshot["commit"],
              "tier": "I0", "mode": "deterministic", "provenance": "deterministic", "level": "static-measured",
              "integrity": inventory["integrity"], "method": inventory["method"], "tree_sha256": tree,
              "tar_sha256": inventory["tar_sha256"], "files": len(sealed), "bytes": sum(len(v) for v in sealed.values()),
              "lab_ref": folder + "/source.tar", "fallback_reason": inventory.get("fallback_reason"), "recorded_at": stamp}
    save_evidence(target, fid, f"I0-{pin[:12]}.json", intake)
    save_evidence(target, fid, f"T0-{pin[:12]}-s{core.SCANNER_VERSION}.json", record)

    def mutate(reg):
        food = reg["foods"][fid]
        food["source"].update(commit=snapshot["commit"], integrity=inventory["integrity"], fetched_at=stamp)
        food["lifecycle"] = "tasted"
        food["sealed"] = {"lab_ref": folder + "/source.tar", "tree_sha256": tree}
    update_json(target, ("registry.json",), mutate, {"schema_version": 1, "foods": {}})
    derived = core.derive(load_evidence(target, fid), [d for d in load_decisions(target) if d.get("food") == fid])
    write_status(target, {**entry, "source": {**source, "commit": snapshot["commit"]}}, "done", 3, headline=derived["headline"])
    update_view(target)
    counts = {k: sum(1 for c in derived["components"] if c["disposition"] == k) for k in core.DISPOSITIONS}
    lines = [f"{fid}: sealed {len(sealed)} files @ {(snapshot['commit'] or 'unverified')[:12]} ({inventory['integrity']}) in LAB_HOME, outside the project",
             f"  nothing extracted, executed or imported; T0 {len(record['checks_run'])} checks",
             f"  flags: {derived['flags']['total']} ({derived['flags']['open_high']} high) · exec {record['exec_class']} · license {record['license']['spdx']}",
             f"  components: absorb {counts['absorb']} · excrete {counts['excrete']} · hold {counts['hold']}",
             f"  verdict: {derived['symbol']} {derived['label']} ({', '.join(derived['reasons'])})"]
    if snapshot.get("fallback_reason"):
        lines.append(f"  fallback tarball used: {core.sanitize_text(snapshot['fallback_reason'], 160)}")

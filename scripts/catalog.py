def http_json(url: str, headers: dict) -> dict:
    request = urllib.request.Request(url, headers=headers)
    with urllib.request.urlopen(request, timeout=30) as response:
        data = response.read(5 * 1024 * 1024)
    value = json.loads(data.decode("utf-8"))
    if not isinstance(value, dict):
        raise ValueError("unexpected response")
    return value


def iso_week(moment: datetime) -> str:
    year, week, _day = moment.isocalendar()
    return f"{year}-W{week:02d}"


def cmd_scout(target: Path, per_query: int = 30, days: int = 7) -> dict:
    moment = datetime.now(timezone.utc)
    since = (moment - timedelta(days=days)).date().isoformat()
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "oaw-catalog/0", "X-GitHub-Api-Version": "2022-11-28"}
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        headers["Authorization"] = "Bearer " + token
    seen, kept, dropped, errors = {}, {}, [], []
    for query in SCOUT_QUERIES:
        url = GITHUB_API + "?" + urllib.parse.urlencode({"q": f"{query} pushed:>={since}", "sort": "stars", "order": "desc",
                                                         "per_page": max(1, min(per_query, 100))})
        try:
            items = http_json(url, headers).get("items") or []
        except (urllib.error.URLError, OSError, ValueError) as exc:
            errors.append(core.sanitize_text(f"{query}: {exc}", 160))
            continue
        for item in items:
            if isinstance(item, dict) and isinstance(item.get("html_url"), str):
                seen.setdefault(item["html_url"], item)
    if errors and not seen:
        raise CatalogError("Scout could not reach GitHub search: " + "; ".join(errors[:2]))
    for url, item in seen.items():
        try:
            source = core.normalize_source(url)
        except core.SourceError:
            dropped.append({"repo": core.sanitize_text(url, 80), "reason": "not a repository URL"})
            continue
        if item.get("archived") or item.get("fork"):
            dropped.append({"repo": source["display"], "reason": "archived or fork"})
            continue
        verdict = core.relevance(item)
        if not verdict["keep"]:
            dropped.append({"repo": source["display"], "reason": verdict["reason"]})
            continue
        kept[source["key"]] = {"key": source["key"], "display": source["display"], "url": source["url"],
                               "description": core.sanitize_text(item.get("description"), 200),
                               "stars": int(item.get("stargazers_count") or 0),
                               "topics": [core.sanitize_text(t, 40) for t in (item.get("topics") or [])[:10]],
                               "relevance": verdict["reason"]}
    week = iso_week(moment)

    def mutate(pool):
        candidates = pool.setdefault("candidates", {})
        for key, item in kept.items():
            current = candidates.setdefault(key, {"first_seen": now_iso(), "status": "candidate", "weeks_seen": []})
            current.update(item, last_seen=now_iso())
            if week not in current["weeks_seen"]:
                current["weeks_seen"].append(week)
        pool["dropped_total"] = int(pool.get("dropped_total", 0)) + len(dropped)
        pool.setdefault("runs", []).append({"at": now_iso(), "week": week, "queries": len(SCOUT_QUERIES), "seen": len(seen),
                                            "kept": len(kept), "dropped": len(dropped), "errors": errors})
        del pool["runs"][:-52]
    update_json(target, ("scout.json",), mutate, {"schema_version": 1, "candidates": {}, "runs": [], "dropped_total": 0})
    update_view(target)
    result = cmd_scout_list(target)
    result["lines"] = [f"scout {week}: {len(seen)} seen · {len(kept)} kept · {len(dropped)} dropped without review"
                       + (f" · {len(errors)} query error(s)" if errors else "")] + result["lines"]
    result.update(status="scouted", kept=len(kept), dropped=dropped, errors=errors)
    return result


def scout_order(pool: dict) -> list:
    return sorted(pool.get("candidates", {}).values(), key=lambda c: (-int(c.get("stars") or 0), c.get("key", "")))


def cmd_scout_list(target: Path) -> dict:
    pool = load_json(catalog_path(target, "scout.json"), {"candidates": {}})
    ordered = scout_order(pool)
    lines = ["rank  stars (queue order only, not quality)  status     repo"]
    lines += [f"{i:>4}  {c.get('stars', 0):>7}  {c.get('status', 'candidate'):10} {core.sanitize_text(c['display'], 60)} · {core.sanitize_text(c.get('description'), 80)}"
              for i, c in enumerate(ordered, 1)]
    lines.append("pick: catalog.py scout pick N [N ...]  (nothing is tasted until you pick and taste)")
    return {"status": "scout", "candidates": ordered, "lines": lines}


def cmd_scout_pick(target: Path, ranks) -> dict:
    pool = load_json(catalog_path(target, "scout.json"), {"candidates": {}})
    ordered = scout_order(pool)
    chosen = []
    for rank in ranks:
        if not 1 <= rank <= len(ordered):
            raise CatalogError(f"No scout candidate #{rank}.")
        chosen.append(ordered[rank - 1])
    result = add_foods(target, [c["url"] for c in chosen], origin="scout", scout={c["key"]: c.get("stars") for c in chosen})
    registry = load_registry(target)
    ids = {e["source"]["key"]: fid for fid, e in registry["foods"].items()}

    def mutate(doc):
        for c in chosen:
            doc["candidates"][c["key"]].update(status="picked", food=ids.get(c["key"]), picked_at=now_iso())
    update_json(target, ("scout.json",), mutate, {"schema_version": 1, "candidates": {}})
    update_view(target)
    return result


# --------------------------------------------------------------------------- view

def view_state(target: Path) -> dict:
    registry = load_registry(target)
    evidence = {fid: load_evidence(target, fid) for fid in registry.get("foods", {})}
    decisions = load_decisions(target)
    policy = load_policy(target)
    plans = {}
    for fid in registry.get("foods", {}):
        derived = core.derive(evidence[fid], [d for d in decisions if d.get("food") == fid])
        historical = [r for r in evidence[fid] if core.evidence_class(r) == "historical"]
        plans[fid] = core.decide_plan(fid, derived, historical, policy)
    builds = load_builds(target)
    effect = load_json(catalog_path(target, "effect.json"), None)
    matches = None
    try:
        files, _manifest = layer_files(target)
        digest = layer_hash(files)
        current = next((b for b in builds.get("builds", []) if b.get("name") == builds.get("current")), None)
        matches = bool(current and current.get("hash") == digest)
        if effect and effect.get("layer_hash") != digest:
            effect = {**effect, "stale": True}
    except (CatalogError, OSError):
        pass
    return {"registry": registry, "evidence": evidence, "decisions": decisions, "policy": policy, "plans": plans,
            "builds": builds, "effect": effect, "scout": load_json(catalog_path(target, "scout.json"), {"candidates": {}}),
            "receipts": load_receipts(target), "current_matches_build": matches}


def refresh_view(target: Path) -> dict:
    view = core.build_view(view_state(target))
    view["generated_at"] = now_iso()
    save_json(target, ("view.json",), view)
    return view


def update_view(target: Path) -> None:
    """Refresh view.json after a change; a view problem never undoes the change itself."""
    try:
        refresh_view(target)
    except (CatalogError, OSError, ValueError) as exc:
        print(f"catalog warning: view.json not refreshed: {exc}", file=sys.stderr)


def cmd_view(target: Path) -> dict:
    view = refresh_view(target)
    lines = [f"OAW {view['release']} · build {view['my_oaw']['current_build'] or 'none recorded'} · foods {len(view['foods'])} · view.json written"]
    for food in view["foods"]:
        v, counts = food["verdict"], food["counts"]
        lines.append(f"  {v['symbol']} {food['id']:28} {v['label']:20} absorb {counts['absorb']} · excrete {counts['excrete']} · hold {counts['hold']}"
                     + (f" · historical {len(food['historical'])}" if food["historical"] else ""))
    return {"status": "view", "path": str(catalog_path(target, "view.json")), "lines": lines}



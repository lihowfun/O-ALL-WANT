def _inside(path: Path, boundary: Path) -> bool:
    try:
        common = os.path.commonpath([os.path.normcase(str(path)), os.path.normcase(str(boundary))])
    except ValueError:
        return False
    return common == os.path.normcase(str(boundary))


def lab_home(target: Path | None = None) -> Path:
    """Per-user data directory outside the project (never a cache directory)."""
    override = os.environ.get("OAW_LAB_HOME")
    if override:
        base = Path(override)
    elif os.name == "nt":
        base = Path(os.environ.get("LOCALAPPDATA") or Path.home() / "AppData" / "Local") / "oaw" / "lab"
    elif sys.platform == "darwin":
        base = Path.home() / "Library" / "Application Support" / "oaw" / "lab"
    else:
        base = Path(os.environ.get("XDG_DATA_HOME") or Path.home() / ".local" / "share") / "oaw" / "lab"
    base = Path(os.path.abspath(base)).resolve()
    if target is not None and (_inside(base, Path(target).resolve()) or _inside(Path(target).resolve(), base)):
        raise CatalogError("LAB_HOME must be outside the project; set OAW_LAB_HOME to another directory.")
    if _inside(base, oaw.framework_root()):
        raise CatalogError("LAB_HOME must be outside the OAW framework checkout.")
    base.mkdir(parents=True, exist_ok=True)
    return base.resolve()


def lab_path(lab: Path, relative: str) -> Path:
    return Path(oaw_common.confined_path(lab, *relative.split("/")))


def lab_write(lab: Path, relative: str, data: bytes, *, readonly: bool = False) -> Path:
    path = lab_path(lab, relative)
    path.parent.mkdir(parents=True, exist_ok=True)
    descriptor, temporary = tempfile.mkstemp(prefix=".oaw-", suffix=".tmp", dir=path.parent)
    try:
        with os.fdopen(descriptor, "wb") as handle:
            handle.write(data)
            handle.flush()
            os.fsync(handle.fileno())
        if readonly:
            os.chmod(temporary, stat.S_IREAD)
        if path.exists():
            os.chmod(path, stat.S_IREAD | stat.S_IWRITE)
        os.replace(temporary, path)
    finally:
        if os.path.exists(temporary):
            os.chmod(temporary, stat.S_IREAD | stat.S_IWRITE)
            os.unlink(temporary)
    return path


def rmtree(path: Path) -> None:
    def retry(function, name, _info):
        os.chmod(name, stat.S_IREAD | stat.S_IWRITE)
        function(name)
    if os.path.lexists(path):
        if sys.version_info >= (3, 12):
            shutil.rmtree(path, onexc=lambda f, n, _e: retry(f, n, None))
        else:
            shutil.rmtree(path, onerror=retry)


def scratch_dir(lab: Path, prefix: str) -> Path:
    root = lab_path(lab, "scratch")
    root.mkdir(parents=True, exist_ok=True)
    return Path(tempfile.mkdtemp(prefix=prefix, dir=root))


def project_key(target: Path) -> str:
    return hashlib.sha256(os.path.normcase(str(target)).encode("utf-8")).hexdigest()[:16]


def private_ref(source: dict) -> str:
    return "private#" + hashlib.sha256(source["key"].encode()).hexdigest()[:8] if core.is_local_source(source) else source["key"]


def pin_label(source: dict) -> str:
    """A repository's commit (7) or a paper's arXiv version; 'unpinned' before a taste."""
    return (source.get("commit") or "")[:7] or source.get("version") or "unpinned"



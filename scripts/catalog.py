def add_foods(target: Path, inputs, *, origin="url", ref=None, scout=None) -> dict:
    batch = core.dedupe_sources(inputs)
    added, existing = [], []

    def mutate(registry):
        foods = registry.setdefault("foods", {})
        taken = {fid: entry["source"]["key"] for fid, entry in foods.items()}
        by_key = {entry["source"]["key"]: fid for fid, entry in foods.items()}
        for item in batch["foods"]:
            source = item["source"]
            if source["key"] in by_key:
                fid = by_key[source["key"]]
                requested = foods[fid].setdefault("requested", [])
                requested.extend(x for x in item["inputs"] if x not in requested)
                del requested[20:]
                existing.append({"id": fid, "inputs": item["inputs"]})
                continue
            fid = core.food_id(source, taken)
            taken[fid], by_key[source["key"]] = source["key"], fid
            stamp = now_iso()
            foods[fid] = {
                "schema_version": 1, "id": fid, "display": source["display"], "origin": origin, "lifecycle": "found",
                "source": {"kind": source["kind"], "key": source["key"], "url": source["url"], "fetch_url": source["fetch_url"],
                           "owner": source["owner"], "repo": source["repo"], "requested_ref": ref or source["ref"],
                           "subdir": source["subdir"], "commit": None, "integrity": None, "fetched_at": None},
                "requested": item["inputs"][:20], "added_at": stamp,
                "intake": {"requested_by": origin, "requested_at": stamp},
                "scout": {"stars": (scout or {}).get(source["key"]), "use": "queue-order-only"},
            }
            added.append(fid)
    update_json(target, ("registry.json",), mutate, {"schema_version": 1, "foods": {}})
    lines = [f"added {fid}" for fid in added]
    lines += [f"merged: {' = '.join(m['inputs'])} (one food: {m['key']})" for m in batch["merges"]]
    lines += [f"already registered: {e['id']} (merged {', '.join(e['inputs'])})" for e in existing]
    lines += [f"refused: {e['input']}: {e['error']}" for e in batch["errors"]]
    if added:
        lines.append("next: catalog.py taste ID  (free, sealed, nothing runs)")
    return {"status": "added" if added else "unchanged", "added": added, "merges": batch["merges"],
            "existing": existing, "errors": batch["errors"], "lines": lines}



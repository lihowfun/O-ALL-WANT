    keep = {target / p for p in ("", ".oaw", ".agents", ".claude", ".agents/skills", ".claude/skills", ".claude/agents",
                                 ".oaw/integrations", ".oaw/catalog", ".oaw/catalog/absorbed", "scripts")}

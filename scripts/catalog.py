def load_registry(target: Path) -> dict:
    return load_json(catalog_path(target, "registry.json"), {"schema_version": 1, "foods": {}})


def resolve_food(registry: dict, ident: str) -> dict:
    foods = registry.get("foods", {})
    if ident in foods:
        return foods[ident]
    try:
        key = core.normalize_source(ident)["key"]
        matches = [e for e in foods.values() if e["source"]["key"] == key]
    except core.SourceError:
        matches = [e for e in foods.values() if e["source"].get("repo", "").casefold() == str(ident).casefold()]
    if len(matches) == 1:
        return matches[0]
    raise CatalogError(f"Unknown food: {core.sanitize_text(ident, 80)!r}; see `catalog.py list`.")


def evidence_dir(target: Path, fid: str) -> Path:
    return catalog_path(target, "evidence", core.slug(fid))


def load_evidence(target: Path, fid: str) -> list:
    folder = evidence_dir(target, fid)
    records = []
    if folder.is_dir():
        for path in sorted(folder.glob("*.json")):
            value = load_json(path, None)
            if isinstance(value, dict):
                records.append(value)
    return records


def save_evidence(target: Path, fid: str, name: str, record: dict) -> str:
    save_json(target, ("evidence", core.slug(fid), name), record)
    return f"evidence/{core.slug(fid)}/{name}"


def load_decisions(target: Path) -> list:
    path = catalog_path(target, "decisions.jsonl")
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        return []
    result = []
    for line in text.splitlines():
        try:
            value = json.loads(line)
        except ValueError:
            continue
        if isinstance(value, dict):
            result.append(value)
    return result


